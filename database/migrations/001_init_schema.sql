  CONSTRAINT qr_codes_lifecycle_status_chk
    CHECK (lifecycle_status IN ('unactivated', 'co_creating', 'activated')),
  CONSTRAINT qr_codes_batch_fk
    FOREIGN KEY (batch_id) REFERENCES app.qr_batches (id) ON DELETE RESTRICT,
  CONSTRAINT qr_codes_access_token_nonempty_chk
    CHECK (access_token IS NULL OR btrim(access_token) <> ''),
  CONSTRAINT qr_codes_updated_at_chk CHECK (updated_at >= created_at)
);

CREATE UNIQUE INDEX qr_codes_access_token_uq
  ON app.qr_codes (access_token) WHERE access_token IS NOT NULL;
CREATE INDEX qr_codes_batch_id_idx ON app.qr_codes (batch_id);
CREATE INDEX qr_codes_lifecycle_status_idx ON app.qr_codes (lifecycle_status);
CREATE INDEX qr_codes_issue_lifecycle_idx ON app.qr_codes (issue_status, lifecycle_status);
CREATE INDEX qr_codes_hidden_idx ON app.qr_codes (hidden);
CREATE INDEX qr_codes_created_at_idx ON app.qr_codes (created_at);

CREATE TABLE app.records (
  qr_id text PRIMARY KEY,
  account_id varchar(32) NOT NULL,
  content text NOT NULL DEFAULT '',
  image_url_snapshot text NOT NULL DEFAULT '',
  image_object_key text,
  image_sha256 char(64),
  phone_snapshot varchar(32) NOT NULL DEFAULT '',
  sealed_at timestamptz,
  show_brand_disclosure boolean NOT NULL DEFAULT false,
  brand_disclosure_text_snapshot text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  CONSTRAINT records_qr_fk
    FOREIGN KEY (qr_id) REFERENCES app.qr_codes (id) ON DELETE RESTRICT,
  CONSTRAINT records_account_fk
    FOREIGN KEY (account_id) REFERENCES app.accounts (id) ON DELETE RESTRICT,
  CONSTRAINT records_image_sha256_format_chk
    CHECK (image_sha256 IS NULL OR image_sha256 ~ '^[0-9a-f]{64}$'),
  CONSTRAINT records_updated_at_chk CHECK (updated_at >= created_at),
  CONSTRAINT records_sealed_at_chk CHECK (sealed_at IS NULL OR sealed_at >= created_at)
);

CREATE INDEX records_account_sealed_idx ON app.records (account_id, sealed_at DESC);
CREATE INDEX records_sealed_at_idx ON app.records (sealed_at);
CREATE INDEX records_image_object_key_idx
  ON app.records (image_object_key) WHERE image_object_key IS NOT NULL;

