  CONSTRAINT operators_updated_at_chk CHECK (updated_at >= created_at)
);

CREATE INDEX operators_role_enabled_idx ON app.operators (role, enabled);

CREATE TABLE app.qr_batches (
  id text PRIMARY KEY,
  name varchar(160) NOT NULL,
  brand_name varchar(160) NOT NULL DEFAULT '',
  note text NOT NULL DEFAULT '',
  disclosure_text text NOT NULL DEFAULT '',
  show_brand_disclosure_default boolean NOT NULL DEFAULT false,
  created_by_operator_id bigint,
  created_by_snapshot varchar(120) NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  CONSTRAINT qr_batches_id_nonempty_chk CHECK (btrim(id) <> ''),
  CONSTRAINT qr_batches_name_nonempty_chk CHECK (btrim(name) <> ''),
  CONSTRAINT qr_batches_creator_fk
    FOREIGN KEY (created_by_operator_id) REFERENCES app.operators (id) ON DELETE RESTRICT,
  CONSTRAINT qr_batches_updated_at_chk CHECK (updated_at >= created_at)
