CREATE INDEX qr_batches_created_at_idx ON app.qr_batches (created_at);

CREATE TABLE app.qr_codes (
  id text PRIMARY KEY,
  issue_status varchar(24) NOT NULL,
  lifecycle_status varchar(24) NOT NULL,
  hidden boolean NOT NULL DEFAULT false,
  batch_id text,
  print_batch_id text,
  qr_image_url_snapshot text NOT NULL DEFAULT '',
  access_token varchar(255),
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  CONSTRAINT qr_codes_id_nonempty_chk CHECK (btrim(id) <> ''),
