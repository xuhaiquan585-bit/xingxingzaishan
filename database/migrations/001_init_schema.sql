CREATE TABLE app.orders (
  id text PRIMARY KEY,
  order_no varchar(80) NOT NULL,
  account_id varchar(32) NOT NULL,
  product_id text,
  openid_snapshot varchar(160) NOT NULL DEFAULT '',
  phone_snapshot varchar(32) NOT NULL DEFAULT '',
  product_snapshot jsonb NOT NULL,
  quantity integer NOT NULL,
  unit_price_cents bigint NOT NULL,
  total_amount_cents bigint NOT NULL,
  status varchar(24) NOT NULL,
  payment_status varchar(24) NOT NULL,
  payment_method varchar(32) NOT NULL DEFAULT '',
  payment_mock boolean NOT NULL DEFAULT false,
  provider_transaction_id varchar(160),
  provider_transaction_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
  paid_at timestamptz,
  receiver_name varchar(120) NOT NULL,
  receiver_phone varchar(32) NOT NULL,
  region varchar(240) NOT NULL,
  address text NOT NULL,
  remark text NOT NULL DEFAULT '',
  express_company varchar(120) NOT NULL DEFAULT '',
  express_no varchar(160) NOT NULL DEFAULT '',
  shipped_at timestamptz,
  refund_status varchar(32) NOT NULL DEFAULT '',
  admin_note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  CONSTRAINT orders_order_no_uq UNIQUE (order_no),
  CONSTRAINT orders_account_fk
    FOREIGN KEY (account_id) REFERENCES app.accounts (id) ON DELETE RESTRICT,
  CONSTRAINT orders_product_fk
    FOREIGN KEY (product_id) REFERENCES app.products (id) ON DELETE RESTRICT,
  CONSTRAINT orders_quantity_chk CHECK (quantity > 0),
  CONSTRAINT orders_unit_price_cents_chk CHECK (unit_price_cents >= 0),
  CONSTRAINT orders_total_amount_cents_chk CHECK (total_amount_cents >= 0),
  CONSTRAINT orders_total_recomputes_chk CHECK (total_amount_cents = unit_price_cents * quantity),
  CONSTRAINT orders_status_chk
    CHECK (status IN ('pending_payment', 'paid', 'shipped', 'completed', 'cancelled', 'refunding', 'refunded')),
  CONSTRAINT orders_payment_status_chk
    CHECK (payment_status IN ('unpaid', 'paid', 'failed', 'refunded')),
  CONSTRAINT orders_updated_at_chk CHECK (updated_at >= created_at),
  CONSTRAINT orders_paid_at_chk CHECK (paid_at IS NULL OR paid_at >= created_at),
  CONSTRAINT orders_shipped_at_chk CHECK (shipped_at IS NULL OR shipped_at >= created_at)
);

CREATE INDEX orders_account_created_idx ON app.orders (account_id, created_at DESC);
CREATE INDEX orders_status_created_idx ON app.orders (status, created_at DESC);
CREATE INDEX orders_payment_status_idx ON app.orders (payment_status);
CREATE INDEX orders_provider_transaction_idx
  ON app.orders (provider_transaction_id) WHERE provider_transaction_id IS NOT NULL;

