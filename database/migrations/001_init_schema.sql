CREATE SCHEMA app;

CREATE TABLE app.schema_migrations (
  version varchar(128) PRIMARY KEY,
  checksum char(64) NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT schema_migrations_checksum_format_chk
    CHECK (checksum ~ '^[0-9a-f]{64}$')
);

CREATE TABLE app.import_runs (
  id uuid PRIMARY KEY,
  source_sha256 char(64) NOT NULL,
  source_label varchar(160) NOT NULL,
  importer_version varchar(64) NOT NULL,
  mode varchar(16) NOT NULL,
  status varchar(24) NOT NULL,
  source_counts jsonb NOT NULL DEFAULT '{}'::jsonb,
  imported_counts jsonb NOT NULL DEFAULT '{}'::jsonb,
  checksum_summary jsonb NOT NULL DEFAULT '{}'::jsonb,
  started_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at timestamptz,
  CONSTRAINT import_runs_source_sha256_uq UNIQUE (source_sha256),
  CONSTRAINT import_runs_source_sha256_format_chk
    CHECK (source_sha256 ~ '^[0-9a-f]{64}$'),
  CONSTRAINT import_runs_mode_chk
    CHECK (mode IN ('dry_run', 'staging', 'final')),
  CONSTRAINT import_runs_status_chk
    CHECK (status IN ('running', 'passed', 'blocked', 'failed')),
  CONSTRAINT import_runs_completed_at_chk
    CHECK (completed_at IS NULL OR completed_at >= started_at)
);

CREATE TABLE app.import_anomalies (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  import_run_id uuid NOT NULL,
  severity varchar(16) NOT NULL,
  category varchar(80) NOT NULL,
  entity_type varchar(80) NOT NULL,
  legacy_reference_hash varchar(32),
  field_name varchar(120),
  candidate_count integer NOT NULL DEFAULT 0,
  blocking boolean NOT NULL DEFAULT true,
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT import_anomalies_import_run_fk
    FOREIGN KEY (import_run_id) REFERENCES app.import_runs (id) ON DELETE RESTRICT,
  CONSTRAINT import_anomalies_severity_chk
    CHECK (severity IN ('info', 'warning', 'error')),
  CONSTRAINT import_anomalies_candidate_count_chk
    CHECK (candidate_count >= 0)
);

CREATE INDEX import_anomalies_run_blocking_idx
  ON app.import_anomalies (import_run_id, blocking, severity);

CREATE TABLE app.accounts (
  id varchar(32) PRIMARY KEY,
  status varchar(24) NOT NULL,
  display_name varchar(120) NOT NULL DEFAULT '',
  avatar_url text NOT NULL DEFAULT '',
  created_from varchar(32) NOT NULL,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  CONSTRAINT accounts_id_nonempty_chk CHECK (btrim(id) <> ''),
  CONSTRAINT accounts_status_chk CHECK (status IN ('active', 'disabled', 'closed')),
  CONSTRAINT accounts_created_from_chk
    CHECK (created_from IN ('web_phone', 'miniapp_openid', 'migration', 'admin_repair')),
  CONSTRAINT accounts_updated_at_chk CHECK (updated_at >= created_at)
);

CREATE INDEX accounts_status_idx ON app.accounts (status);
CREATE INDEX accounts_created_at_idx ON app.accounts (created_at);

CREATE TABLE app.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_id text,
  account_id varchar(32) NOT NULL,
  phone varchar(32),
  openid varchar(160),
  unionid varchar(160),
  source varchar(32) NOT NULL,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  CONSTRAINT users_legacy_id_uq UNIQUE (legacy_id),
  CONSTRAINT users_account_fk
    FOREIGN KEY (account_id) REFERENCES app.accounts (id) ON DELETE RESTRICT,
  CONSTRAINT users_identity_present_chk
    CHECK (phone IS NOT NULL OR openid IS NOT NULL OR unionid IS NOT NULL),
  CONSTRAINT users_phone_nonempty_chk CHECK (phone IS NULL OR btrim(phone) <> ''),
  CONSTRAINT users_openid_nonempty_chk CHECK (openid IS NULL OR btrim(openid) <> ''),
  CONSTRAINT users_unionid_nonempty_chk CHECK (unionid IS NULL OR btrim(unionid) <> ''),
  CONSTRAINT users_source_chk
    CHECK (source IN ('web', 'miniapp', 'web+miniapp', 'migration')),
  CONSTRAINT users_updated_at_chk CHECK (updated_at >= created_at)
);

CREATE INDEX users_account_id_idx ON app.users (account_id);
CREATE UNIQUE INDEX users_phone_uq
  ON app.users (phone) WHERE phone IS NOT NULL;
CREATE UNIQUE INDEX users_openid_uq
  ON app.users (openid) WHERE openid IS NOT NULL;
CREATE INDEX users_unionid_idx
  ON app.users (unionid) WHERE unionid IS NOT NULL;

CREATE TABLE app.operators (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_id text,
  username varchar(120) NOT NULL,
  password_hash text NOT NULL,
  role varchar(24) NOT NULL,
  name varchar(120) NOT NULL DEFAULT '',
  enabled boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  CONSTRAINT operators_legacy_id_uq UNIQUE (legacy_id),
  CONSTRAINT operators_username_uq UNIQUE (username),
  CONSTRAINT operators_username_nonempty_chk CHECK (btrim(username) <> ''),
  CONSTRAINT operators_password_hash_nonempty_chk CHECK (btrim(password_hash) <> ''),
