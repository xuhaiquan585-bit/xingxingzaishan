CREATE TABLE app.miniapp_content (
  id smallint PRIMARY KEY,
  home_title varchar(240) NOT NULL,
  home_subtitle text NOT NULL,
  logo_image text NOT NULL DEFAULT '',
  home_banner_image text NOT NULL DEFAULT '',
  home_slides jsonb NOT NULL DEFAULT '[]'::jsonb,
  scene_cards jsonb NOT NULL DEFAULT '[]'::jsonb,
  project_title varchar(240) NOT NULL,
  project_body text NOT NULL,
  brand_story_title varchar(240) NOT NULL,
  brand_story_body text NOT NULL,
  consult_label varchar(120) NOT NULL,
  consult_url text NOT NULL DEFAULT '',
  share_title varchar(240) NOT NULL,
  share_description text NOT NULL,
  updated_by_operator_id bigint,
  updated_by_snapshot varchar(120) NOT NULL DEFAULT '',
  updated_at timestamptz NOT NULL,
  CONSTRAINT miniapp_content_singleton_chk CHECK (id = 1),
  CONSTRAINT miniapp_content_operator_fk
    FOREIGN KEY (updated_by_operator_id) REFERENCES app.operators (id) ON DELETE RESTRICT,
  CONSTRAINT miniapp_content_slides_array_chk
    CHECK (jsonb_typeof(home_slides) = 'array'),
  CONSTRAINT miniapp_content_scene_cards_array_chk
    CHECK (jsonb_typeof(scene_cards) = 'array')
);

CREATE TABLE app.audit_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_type varchar(32) NOT NULL,
  actor_reference varchar(160),
  actor_reference_hash char(64),
  action varchar(120) NOT NULL,
  entity_type varchar(80) NOT NULL,
  entity_id varchar(200),
  entity_reference_hash char(64),
  request_method varchar(16),
  request_path varchar(240),
  result_status varchar(32) NOT NULL,
  ip_hash varchar(64),
  user_agent_family varchar(120),
  duration_ms integer,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT audit_events_actor_type_chk
    CHECK (actor_type IN ('system', 'account', 'operator', 'external')),
  CONSTRAINT audit_events_result_status_chk
    CHECK (result_status IN ('success', 'denied', 'failed')),
  CONSTRAINT audit_events_actor_reference_hash_format_chk
    CHECK (actor_reference_hash IS NULL OR actor_reference_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT audit_events_entity_reference_hash_format_chk
    CHECK (entity_reference_hash IS NULL OR entity_reference_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT audit_events_duration_ms_chk CHECK (duration_ms IS NULL OR duration_ms >= 0),
  CONSTRAINT audit_events_entity_reference_chk
    CHECK (entity_id IS NOT NULL OR entity_reference_hash IS NOT NULL)
);

CREATE INDEX audit_events_entity_created_idx
  ON app.audit_events (entity_type, entity_id, created_at DESC);
CREATE INDEX audit_events_action_created_idx ON app.audit_events (action, created_at DESC);

CREATE TABLE app.outbox_jobs (
  id uuid PRIMARY KEY,
  job_type varchar(80) NOT NULL,
  aggregate_type varchar(80) NOT NULL,
  aggregate_id varchar(200) NOT NULL,
  idempotency_key varchar(240) NOT NULL,
  payload jsonb NOT NULL,
  status varchar(24) NOT NULL,
  attempt_count integer NOT NULL DEFAULT 0,
  available_at timestamptz NOT NULL,
  locked_at timestamptz,
  locked_by varchar(160),
  last_error text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  CONSTRAINT outbox_jobs_idempotency_key_uq UNIQUE (idempotency_key),
  CONSTRAINT outbox_jobs_status_chk
    CHECK (status IN ('pending', 'processing', 'succeeded', 'failed')),
  CONSTRAINT outbox_jobs_attempt_count_chk CHECK (attempt_count >= 0),
  CONSTRAINT outbox_jobs_lock_pair_chk
    CHECK ((locked_at IS NULL AND locked_by IS NULL) OR (locked_at IS NOT NULL AND locked_by IS NOT NULL)),
  CONSTRAINT outbox_jobs_updated_at_chk CHECK (updated_at >= created_at)
);

CREATE INDEX outbox_jobs_status_available_idx
  ON app.outbox_jobs (status, available_at, created_at);
CREATE INDEX outbox_jobs_aggregate_idx
  ON app.outbox_jobs (aggregate_type, aggregate_id, created_at DESC);
